			<el-input-number v-model="ruleForm.dianpumianji" placeholder="面积㎡" :readonly="ro.dianpumianji"></el-input-number>
          </el-form-item>
          <el-form-item :style='{"padding":"10px","margin":"0 0 10px","background":"none"}' label="租金" prop="zujin">
